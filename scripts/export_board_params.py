"""Write c/board/board_params.h: the constants of the thesis wing wire (heat-only preset) as C initialisers for the board layer.

python scripts/export_board_params.py        (needs nothing but the Python package; the constants are the ones the tests use)
"""
import os
import sys
from dataclasses import asdict
from pathlib import Path
os.environ.update(SMA_D_MM="2", SMA_IMAX="35", SMA_SPRING_K="6.36", SMA_SIG="2.2", SMA_NO_HOMING="1")
sys.path.insert(0, str(Path(__file__).resolve().parent))
import evaluate_heatonly as eh                                   # noqa: F401  (sets the heat-only configuration)
import evaluate_controller as ev
from sma_control.loading import UniaxialMEFF
from sma_control.safety import SafetyCfg
from sma_control.spring import BiasSpring

CFG_ORDER = ["Ts", "Kp", "Ki", "k_soft", "dTdt_max", "margin_up", "margin_dn", "T_safe_above_fs", "Kr", "Ki_r", "Kr_dn", "Ki_r_dn", "tau_filt", "Kp_hold",
             "Ki_hold", "drdt_up", "dn_frac", "Kaw", "db_start", "db_done", "T_amb_est", "T_limit_above_Af", "T_abs_max", "T_limit_expand_rate",
             "learn_margin", "hold_step", "hold_drift", "hold_below_As", "sigma_unc", "overshoot_exit", "heat_only", "creep_confirm", "creep_rate",
             "creep_detect", "q_tau", "approach_gain", "approach_span", "approach_min_rate", "fast_detect", "creep_pcap", "settle_dr", "settle_s",
             "full_min", "near_tol", "drop_tol", "reset_r", "reset_still_s", "reset_timeout", "tol_bound"]
SAFE_ORDER = ["T_trip", "T_disagree", "T_disagree_dyn", "h_min", "h_max", "dT_amb", "band", "T_lat_lo", "stall_dT", "t_stall", "stall_frac", "I_tol_abs",
              "I_tol_rel", "t_I_mismatch", "R_tol", "mc_min_frac", "mc_max_frac", "lat_max_frac", "tc_lag_max"]


def g(x):
    return f"{float(x):.9g}"


def main(out):
    p, cfg, sc = ev.NOM, ev.make_cfg(), SafetyCfg()
    u, M = UniaxialMEFF(p.meff), p.meff
    K = BiasSpring(ev.SIG, ev.K_SPRING).K(p)
    cd = asdict(cfg)
    L = ["/* generated by scripts/export_board_params.py: thesis wing wire (2 mm x 200 mm), heat-only preset.  Do not edit. */",
         "#ifndef BOARD_PARAMS_H", "#define BOARD_PARAMS_H", '#include "../sma.h"', "",
         "static const sma_wire_t BOARD_WIRE = { " + ", ".join(g(x) for x in (p.L, p.A, p.surface, p.heat_capacity, p.latent_total, p.rho_eM, p.rho_eA, p.h, p.Imax)) + " };",
         "static const sma_meff_t BOARD_MEFF = { " + ", ".join(g(x) for x in (M.T0, M.R, M.beta, M.eps_L, M.h, M.m, u.E_A, u.E_M)) + " };",
         "static const sma_cfg_t BOARD_CFG = { " + ", ".join(g(cd[k]) for k in CFG_ORDER) + " };",
         "static const sma_safety_cfg_t BOARD_SAFETY = { " + ", ".join(g(getattr(sc, k)) for k in SAFE_ORDER) + f", {g(sc.T_range[0])}, {g(sc.T_range[1])}, {g(sc.t_tc_freeze)}, {g(sc.t_d_freeze)}, {g(sc.stall_learn_frac)}, {sc.n_freeze} }};",
         f"#define BOARD_SIGMA {g(ev.SIG)}f", f"#define BOARD_K_SPRING {g(K)}f",
         f"#define BOARD_D_COLD_MM {g(ev.make_plant(p, 22.0, 1.0, ev.SIG).disp_mm(ev.SIG))}f", "#endif", ""]
    Path(out).write_text("\n".join(L))


if __name__ == "__main__":
    main(Path(__file__).resolve().parents[1] / "c" / "board" / "board_params.h")
    print("wrote c/board/board_params.h")
